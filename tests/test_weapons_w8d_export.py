def broken(world, capsys, name, edit):
    _, _, good = export(world, capsys, "--roles", "all", "--attachments", name=f"good_{name}.json")
    doc = doc_of(good)
    edit(by_id(doc), doc)
    path = world["out"] / f"bad_{name}.json"
    with open(path, "w", encoding="utf-8", newline="\n") as fh:  # the validator wants LF (and would report only that otherwise)
        fh.write(json.dumps(doc, indent=1, sort_keys=True) + "\n")
    return validate(world, capsys, path)


