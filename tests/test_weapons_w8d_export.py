def test_item_frame_points_are_baked_through_each_records_own_basis_literals(world, capsys):
    _, _, out = export(world, capsys, "--roles", "all", "--attachments", name="item.json")
    recs = by_id(doc_of(out))
    alpha, mag = recs[ALPHA], recs[MAG]
    assert alpha["geometry"]["item_basis"] == [[-1, 0, 0], [0, 0, 1], [0, 1, 0]]
    assert mag["geometry"]["item_basis"] == [[1, 0, 0], [0, 0, 1], [0, -1, 0]]
    optic = alpha["geometry"]["mounts"]["optic"]
    assert optic["point"] == [-0.005, -0.05, 0.1] and optic["forward"] == [0.0, 0.0, 1.0] and optic["up"] == [0.0, 1.0, 0.0]
    assert optic["occupied_by"] == ["SM_Wep_Rifle_Alpha_01_Scope"]  # names, not coordinates: preserved
    anchor = mag["attachment"]["anchor"]
    assert anchor["point"] == [0.0, 0.0, 0.0] and anchor["forward"] == [0.0, 1.0, 0.0] and anchor["up"] == [0.0, 0.0, 1.0]
    assert anchor["up"] != [0.0, 0.0, -1.0]  # what baking the part through the host's basis would give


def test_item_frame_equals_basis_times_asset_point_for_every_record_within_1e_4(world, capsys):
    _, _, item = export(world, capsys, "--roles", "all", "--attachments", name="i.json")
    _, _, asset = export(world, capsys, "--roles", "all", "--attachments", "--frame", "asset", name="a.json")
    items, assets = by_id(doc_of(item)), by_id(doc_of(asset))
    frames = 0
    for rid, rec in items.items():
        geom = rec["geometry"]
        if geom is None:
            continue
        basis = np.asarray(geom["item_basis"], dtype=float)  # this record's own, for its own frames
        a_geom = assets[rid]["geometry"]
        pairs = []
        if geom.get("mounts"):
            pairs += [(geom["mounts"][s], a_geom["mounts"][s]) for s in geom["mounts"] if geom["mounts"][s]["point"] is not None]
        att = rec.get("attachment")
        if att and att["anchor"]:
            pairs.append((att["anchor"], assets[rid]["attachment"]["anchor"]))
        for baked, raw in pairs:
            for key in ("point", "forward", "up"):
                assert np.allclose(baked[key], basis @ np.asarray(raw[key]), atol=1e-4, rtol=0), (rid, key)
            frames += 1
    assert frames >= 40  # 35 anchors plus the measured mounts: the loop really ran
    # scalars never move
    for rid, rec in items.items():
        att = rec.get("attachment")
        if att and att["footprint"]:
            assert att["footprint"] == assets[rid]["attachment"]["footprint"]
        for slot, m in ((rec["geometry"] or {}).get("mounts") or {}).items():
            raw = assets[rid]["geometry"]["mounts"][slot]
            assert (m["span_m"], m["bore_d_m"], m["occupied_by"], m["source"]) == (raw["span_m"], raw["bore_d_m"],
                                                                                      raw["occupied_by"], raw["source"])


def test_placement_still_holds_in_the_item_frame_when_each_record_uses_its_own_basis(world, capsys):
    # A consumer places a part with the baked frames and applies each record's own item_basis to its own mesh. That must give
    # the host-item-frame position the asset-frame placement gives: B_host * place_asset(v) == place_item(B_part * v).
    _, _, item = export(world, capsys, "--roles", "all", "--attachments", name="p_i.json")
    _, _, asset = export(world, capsys, "--roles", "all", "--attachments", "--frame", "asset", name="p_a.json")
    items, assets = by_id(doc_of(item)), by_id(doc_of(asset))
    part_i, part_a, host_i, host_a = items[MAG], assets[MAG], items[ALPHA], assets[ALPHA]
    b_part = np.asarray(part_i["geometry"]["item_basis"], dtype=float)
    b_host = np.asarray(host_i["geometry"]["item_basis"], dtype=float)
    assert not np.array_equal(b_part, b_host)  # a part and its host differ here: the test has teeth
    m_asset = place(part_a["attachment"]["anchor"], host_a["geometry"]["mounts"]["magazine"])
    m_item = place(part_i["attachment"]["anchor"], host_i["geometry"]["mounts"]["magazine"])
    for v in ([0.0, 0.0, 0.0], [0.01, -0.12, 0.02], [0.05, 0.1, -0.07]):
        want = b_host @ (m_asset @ np.append(v, 1.0))[:3]
        got = (m_item @ np.append(b_part @ np.asarray(v), 1.0))[:3]
        assert np.allclose(got, want, atol=1e-4, rtol=0), v


