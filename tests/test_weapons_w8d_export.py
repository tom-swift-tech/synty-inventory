"""W8d: ``weapons export --attachments`` (docs/weapon_attachments.md 7; AC77).

World: ``w8d_world`` (the review_helpers packs plus FAKE_Attach, FAKE_Mount, FAKE_CompA, FAKE_CompB). The default-export half is
pinned against two files the UNTOUCHED W7 tree wrote (``w8d_w7_attach_default_export.json`` and ``w8d_w7_attach_roles_all_export.json``,
regenerated by ``w8d_gen_reference.py``), so "byte-identical to W7" is measured, not assumed. Numbers below are literals worked out
from the fixture meshes, not read back from the code under test:

* FAKE_CompA/Alpha is the one host whose body is turned a quarter turn about X; its ``item_basis`` is rows (-1,0,0), (0,0,1), (0,1,0),
  i.e. item = (-x, z, y). Its optic seat is at asset (0.005, 0.1, -0.05) with forward (0,1,0) and up (0,0,1), so in the item frame it is
  (-0.005, -0.05, 0.1), forward (0,0,1), up (0,1,0): forward +Z and up +Y, as an item frame has them.
* FAKE_CompA/Rifle_Mag_01's own ``item_basis`` is rows (1,0,0), (0,0,1), (0,-1,0), i.e. item = (x, z, -y). Its anchor is at the
  origin with forward (0,0,1) and up (0,-1,0), so its item-frame anchor has forward (0,1,0) and up (0,0,1). Baked through the HOST's
  (Alpha's) basis instead, the up would be (0,0,-1): the mutation the literal test below catches.
"""

