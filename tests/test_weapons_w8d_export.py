def export(world, capsys, *flags, name="snap.json", packs=PACKS):
    out = world["out"] / name
    code, res = H.run(world["cfg"], capsys,
                      ["weapons", "export", "--game", "ref", "--packs", packs, *flags, "--out", str(out)])
    return code, res, out


def doc_of(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def text_of(path: Path) -> str:
    return path.read_bytes().decode("utf-8").replace("\r\n", "\n")  # a CRLF checkout is the same file


def reference(name: str) -> str:
    return (FIX / name).read_bytes().decode("utf-8").replace("\r\n", "\n")


def by_id(doc: dict) -> dict:
    return {w["id"]: w for w in doc["weapons"]}


def validate(world, capsys, snapshot: Path):
    return H.run(world["cfg"], capsys, ["weapons", "validate", "--snapshot", str(snapshot)])


